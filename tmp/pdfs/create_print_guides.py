W, H = A4
L, R = 42, W - 42
style = ParagraphStyle('body', fontName='Arial', fontSize=10.3, leading=14, spaceAfter=0)
style_b = ParagraphStyle('bold', parent=style, fontName='Arial-Bold')

class Guide:
    def __init__(self, filename, title):
        self.c = canvas.Canvas(str(OUT / filename), pagesize=A4)
        self.c.setTitle(title)
        self.c.setAuthor('PartyCRM')
        self.title = title
        self.page = 0
    def start(self, subtitle):
        self.page += 1
        self.y = H - 44
        self.c.setFont('Arial', 9)
        self.c.drawString(L, self.y, 'PARTYCRM  /  ПАМЯТКА ДЛЯ ПЕЧАТИ')
        self.y -= 29
        self.text(self.title, size=19, bold=True, leading=23)
        self.text(subtitle, size=10, leading=14)
        self.y -= 7
        self.c.line(L, self.y, R, self.y)
        self.y -= 15
    def text(self, text, size=None, bold=False, leading=None, indent=0):
        st = ParagraphStyle('p', parent=style_b if bold else style,
                            fontSize=size or 10.3, leading=leading or 14)
        p = Paragraph(text, st)
        _, h = p.wrap(R-L-indent, 1000)
        if self.y-h < 48:
            raise ValueError(f'Page overflow: {self.title}, page {self.page}, {text[:50]}')
        p.drawOn(self.c, L+indent, self.y-h)
        self.y -= h+6
    def section(self, title):
        self.y -= 6
        self.text(title, size=12, bold=True, leading=16)
    def check(self, title, detail):
        self.c.rect(L, self.y-10, 8, 8, stroke=1, fill=0)
        self.text(f'<b>{title}</b> {detail}', indent=17)
    def notes(self, label, count=2):
        self.text(label, size=9)
        for _ in range(count):
            self.y -= 13
            self.c.setStrokeColor(HexColor('#999999'))
            self.c.line(L, self.y, R, self.y)
            self.c.setStrokeColor(HexColor('#000000'))
        self.y -= 8
    def end(self):
        self.c.setFont('Arial', 8)
        self.c.drawString(L, 28, 'Подготовлено 03.11.2026  •  А4, масштаб 100%, чёрно-белая печать')
        self.c.drawRightString(R, 28, f'{self.page} / 2')
        self.c.showPage()
    def save(self):
        self.c.save()

